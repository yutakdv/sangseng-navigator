/** 나머지 조사 쌍은 받침 유무만 따르므로 대표 두 값으로만 확인한다 */
const PAIR_CASES = [
  ["편의점", "은/는", "편의점은"],
  ["카페", "은/는", "카페는"],
  ["편의점", "이/가", "편의점이"],
  ["카페", "이/가", "카페가"],
  ["편의점", "와/과", "편의점과"],
  ["카페", "와/과", "카페와"],
  ["편의점", "이나/나", "편의점이나"],
  ["카페", "이나/나", "카페나"],
  // ㄹ 받침은 "(으)로"에서만 예외다 — 다른 쌍에서는 받침으로 센다
  ["서울", "은/는", "서울은"],
  ["0.48", "이/가", "0.48이"],
];

let failed = 0;
const check = (label, actual, expected) => {
  if (actual === expected) return;
  failed += 1;
  console.error(`  실패 ${label}: 기대 "${expected}" · 실제 "${actual}"`);
};

for (const [input, expectedFinal, expectedEul, expectedRo] of CASES) {
  check(`finalConsonant("${input}")`, finalConsonant(input), expectedFinal);
  check(`josa("${input}", 을/를)`, josa(input, "을/를"), expectedEul);
  check(`josa("${input}", 으로/로)`, josa(input, "으로/로"), expectedRo);
}
for (const [input, pair, expected] of PAIR_CASES) {
  check(`josa("${input}", ${pair})`, josa(input, pair), expected);
}
check('particle("편의점", 을/를)', particle("편의점", "을/를"), "을");

const total = CASES.length * 3 + PAIR_CASES.length + 1;
if (failed) {
  console.error(`조사 유틸 검증 실패 — ${total}건 중 ${failed}건 불일치`);
  process.exit(1);
}
console.log(`조사 유틸 검증 통과 — ${total}건 전부 일치 (입력 ${CASES.length + PAIR_CASES.length}종)`);
